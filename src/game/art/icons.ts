export type IconName = keyof typeof ICONS
export const ICON_SIZE = 14

export function renderIcon(name: string): Grid {
  const def = ICONS[name] ?? ICONS.sparkle
  const g = makeGrid(ICON_SIZE, ICON_SIZE)
  paint(g, [[0, 0, def.lines]], def.pal, 1, 1)
  const o = outline(g)
  if (def.overlay) paint(o, [[0, 0, def.overlay]], def.overlayPal ?? {}, 1, 1)
  return o
}

export const hasIcon = (name: string) => name in ICONS
